
-- 1. Registered users
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. One fantasy team per user per season
CREATE TABLE fantasy_teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    season_year INT NOT NULL,
    budget_remaining NUMERIC(6,2) NOT NULL DEFAULT 100.00
        CHECK (budget_remaining >= 0),
    free_transfers_available SMALLINT NOT NULL DEFAULT 2
        CHECK (free_transfers_available BETWEEN 0 AND 3),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, season_year)
);

-- 3. Drivers currently selected for each fantasy team
-- Driver IDs come from our chosen F1 data provider.
CREATE TABLE fantasy_team_drivers (
    fantasy_team_id BIGINT NOT NULL
        REFERENCES fantasy_teams(id) ON DELETE CASCADE,
    driver_external_id VARCHAR(100) NOT NULL,
    is_captain BOOLEAN NOT NULL DEFAULT FALSE,
    selected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (fantasy_team_id, driver_external_id)
);

-- 4. Current fantasy prices, owned by our application
CREATE TABLE driver_prices (
    season_year INT NOT NULL,
    driver_external_id VARCHAR(100) NOT NULL,
    current_price NUMERIC(6,2) NOT NULL
        CHECK (current_price > 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (season_year, driver_external_id)
);

-- 5. Historical record of driver price changes
CREATE TABLE driver_price_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_year INT NOT NULL,
    driver_external_id VARCHAR(100) NOT NULL,
    race_external_id VARCHAR(100),
    old_price NUMERIC(6,2) NOT NULL CHECK (old_price > 0),
    new_price NUMERIC(6,2) NOT NULL CHECK (new_price > 0),
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (season_year, driver_external_id)
        REFERENCES driver_prices(season_year, driver_external_id)
);

-- 6. Record of completed transfers
CREATE TABLE transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fantasy_team_id BIGINT NOT NULL
        REFERENCES fantasy_teams(id) ON DELETE CASCADE,
    sold_driver_external_id VARCHAR(100) NOT NULL,
    bought_driver_external_id VARCHAR(100) NOT NULL,
    race_external_id VARCHAR(100) NOT NULL,
    sold_price NUMERIC(6,2) NOT NULL CHECK (sold_price > 0),
    bought_price NUMERIC(6,2) NOT NULL CHECK (bought_price > 0),
    points_penalty NUMERIC(6,2) NOT NULL DEFAULT 0
        CHECK (points_penalty >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (sold_driver_external_id <> bought_driver_external_id)
);

-- 7. Finalized fantasy points per team per race
CREATE TABLE race_scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fantasy_team_id BIGINT NOT NULL
        REFERENCES fantasy_teams(id) ON DELETE CASCADE,
    race_external_id VARCHAR(100) NOT NULL,
    race_name VARCHAR(150) NOT NULL,
    points NUMERIC(8,2) NOT NULL DEFAULT 0,
    scoring_version INT NOT NULL DEFAULT 1,
    finalized_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (fantasy_team_id, race_external_id)
);

-- 8. Leagues created by users
CREATE TABLE leagues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    invite_code VARCHAR(20) NOT NULL UNIQUE,
    creator_id BIGINT NOT NULL REFERENCES users(id),
    season_year INT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 9. Users participating in leagues
CREATE TABLE league_members (
    league_id BIGINT NOT NULL
        REFERENCES leagues(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (league_id, user_id)
);

-- Indexes for common lookups
CREATE INDEX idx_fantasy_teams_user
    ON fantasy_teams(user_id);

CREATE INDEX idx_race_scores_team
    ON race_scores(fantasy_team_id);

CREATE INDEX idx_race_scores_race
    ON race_scores(race_external_id);

CREATE INDEX idx_league_members_user
    ON league_members(user_id);

CREATE INDEX idx_transfers_team
    ON transfers(fantasy_team_id);

CREATE INDEX idx_price_history_driver
    ON driver_price_history(season_year, driver_external_id);
